"""Generate publication version text from python/pyproject.toml only."""
import argparse
from pathlib import Path
import re
try:
    import tomllib
except ModuleNotFoundError:  # Python 3.10 wheel lane
    import tomli as tomllib

ROOT = Path(__file__).resolve().parents[1]


def version(root=ROOT):
    value = tomllib.loads((root / "python/pyproject.toml").read_text("utf-8"))["project"]["version"]
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", value):
        raise ValueError(f"Release version must be final major.minor.patch: {value!r}")
    return value


def generated(root=ROOT):
    v = version(root)
    major, minor, patch = v.split(".")
    yield "src/eqnedit64_version.h", (
        '#pragma once\n\n/* Generated by tools/release_version.py. */\n'
        f'#define EQNEDIT64_VERSION_MAJOR {major}\n'
        f'#define EQNEDIT64_VERSION_MINOR {minor}\n'
        f'#define EQNEDIT64_VERSION_PATCH {patch}\n'
        f'#define EQNEDIT64_VERSION_TUPLE {major},{minor},{patch},0\n'
        f'#define EQNEDIT64_VERSION_TEXT "{v}"\n'
        f'#define EQNEDIT64_VERSION_TEXT_W L"{v}"\n')
    for name, pattern, replacement in [
        ("web/equation-editor.js", r'(?m)^  var BUILD = .*?;$', f'  var BUILD = "{v}";'),
        ("README.md", r'(?m)^Source version:.*$', f'Source version: **{v}**.'),
        ("python/README.md", r'(?m)^Source version:.*$', f'Source version: **{v}**. Windows wheels contain the native extension,'),
        ("python/src/eqnedit64/__init__.py", r'(?m)^__version__ = .*$', f'__version__ = "{v}"'),
    ]:
        text = (root / name).read_text("utf-8")
        text, count = re.subn(pattern, lambda _: replacement, text)
        if count != 1:
            raise ValueError(f"Expected exactly one version field in {name}, found {count}")
        yield name, text


def generate(root=ROOT, check=False):
    stale = []
    for name, text in generated(root):
        path = root / name
        if path.read_text("utf-8") != text:
            stale.append(name)
            if not check:
                path.write_text(text, encoding="utf-8", newline="\n")
    if check and stale:
        raise ValueError(f"Regenerate release version fields: {stale}")


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true")
    p.add_argument("--print-version", action="store_true")
    args = p.parse_args()
    if args.print_version:
        print(version())
    else:
        generate(check=args.check)


if __name__ == "__main__":
    main()
